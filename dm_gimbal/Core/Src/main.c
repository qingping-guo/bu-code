/**
  * @brief  The application entry point.
  * @retval int
  */
int main(void)
{

  /* USER CODE BEGIN 1 */

  /* USER CODE END 1 */

  /* MPU Configuration--------------------------------------------------------*/
  MPU_Config();

  /* Enable the CPU Cache */

  /* Enable I-Cache---------------------------------------------------------*/
  SCB_EnableICache();

  /* Enable D-Cache---------------------------------------------------------*/
  SCB_EnableDCache();

  /* MCU Configuration--------------------------------------------------------*/

  /* Reset of all peripherals, Initializes the Flash interface and the Systick. */
  HAL_Init();

  /* USER CODE BEGIN Init */
  // 添加以下初始化
  CoreDebug->DEMCR |= CoreDebug_DEMCR_TRCENA_Msk;
  DWT->CYCCNT = 0;
  DWT->CTRL |= DWT_CTRL_CYCCNTENA_Msk;
  /* USER CODE END Init */

  /* Configure the system clock */
  SystemClock_Config();

  /* Configure the peripherals common clocks */
  PeriphCommonClock_Config();

  /* USER CODE BEGIN SysInit */
  SCB->CPACR |= ((3UL << 10*2)|(3UL << 11*2));
  /* USER CODE END SysInit */

  /* Initialize all configured peripherals */
  MX_GPIO_Init();
  MX_DMA_Init();
  MX_SPI2_Init();
  MX_ADC1_Init();
  MX_TIM3_Init();
  MX_FDCAN1_Init();
  MX_FDCAN2_Init();
  MX_FDCAN3_Init();
  MX_UART5_Init();
  MX_UART7_Init();
  MX_USART1_UART_Init();
  MX_USART10_UART_Init();
  /* USER CODE BEGIN 2 */
  // 1. 纯硬件初始化留在这里。
  // 此时系统是“聋子”，不管外面电机怎么发数据都不会进中断。
  // 你的 BMI088 可以安心使用内部的 Delay_ms 慢慢校准。
  //
  /* 【复位原因自检】
     如果串口"打一会儿就没了"，最隐蔽的一种可能是芯片复位了（比如硬件抖动、
     电源跌落、栈溢出踩到复位相关寄存器），而人眼只看到"打印停了"。
     这里把 RCC 的复位标志打出来：正常上电只会出现一次 POR/PIN，
     若运行中反复出现新的一行 RESET CAUSE，就说明板子在不停复位。
     打完立刻清标志，这样下一次复位能被准确区分。 */
  {
      const char *rst =
          __HAL_RCC_GET_FLAG(RCC_FLAG_IWDG1RST) ? "IWDG"  :
          __HAL_RCC_GET_FLAG(RCC_FLAG_WWDG1RST) ? "WWDG"  :
          __HAL_RCC_GET_FLAG(RCC_FLAG_SFTRST)   ? "SOFT"  :
          __HAL_RCC_GET_FLAG(RCC_FLAG_LPWR1RST) ? "LPWR"  :
          __HAL_RCC_GET_FLAG(RCC_FLAG_BORRST)   ? "BOR"   :
          __HAL_RCC_GET_FLAG(RCC_FLAG_PINRST)   ? "PIN"   :
          __HAL_RCC_GET_FLAG(RCC_FLAG_PORRST)   ? "POR"   : "UNKNOWN";

      dbg_printf("### RESET CAUSE: %s (RSR=0x%08lX) ###\r\n", rst, (unsigned long)RCC->RSR);
      __HAL_RCC_CLEAR_RESET_FLAGS();
  }

  // 【启动 banner：决定性分界测试】
  // 在 RTOS 启动前，用阻塞方式打一行（不经过 DMA，不可能被丢弃）。
  //   能看到这行 → 串口10 / USB-TTL / 接线 / 115200 全都正常，
  //                问题一定在任务调度或后续任务里；
  //   看不到这行 → 是硬件接线或波特率问题，跟 RTOS 无关。
  dbg_printf("\r\n### BOOT OK ### USART10 alive @115200\r\n");

  MCU_Init();

  // 【波特率自检】把算出来的 BRR 和反推波特率打出来，一眼确认串口1 配置对不对
  dbg_printf("### PCLK2=%lu Hz | USART1 BRR=%lu | real baud=%lu\r\n",
             (unsigned long)HAL_RCC_GetPCLK2Freq(),
             (unsigned long)USART1->BRR,
             (unsigned long)(HAL_RCC_GetPCLK2Freq() / (USART1->BRR ? USART1->BRR : 1)));
  /* USER CODE END 2 */

  /* Call init function for freertos objects (in cmsis_os2.c) */
  MX_FREERTOS_Init();

  /* Start scheduler */
  osKernelStart();

  /* We should never get here as control is now taken by the scheduler */

  /* Infinite loop */
  /* USER CODE BEGIN WHILE */
  while (1)
  {

    /* USER CODE END WHILE */

    /* USER CODE BEGIN 3 */
    // usart_printf("hello\r\n");   // 加上 \r 保证光标回到行首
    // HAL_Delay(5);            // 强行改成半秒发一次，排除洪水攻击
  }
  /* USER CODE END 3 */
}

